create or replace function public.accept_connection_request(request_id uuid)
returns uuid language plpgsql security definer set search_path=public as $$
declare r public.connection_requests%rowtype; c uuid;
begin
 select * into r from public.connection_requests where id=request_id and receiver_id=auth.uid() and status='pending' for update;
 if not found then raise exception 'Request not found or already handled'; end if;
 insert into public.connections(user_id,connected_user_id) values(auth.uid(),r.sender_id) on conflict do nothing;
 insert into public.connections(user_id,connected_user_id) values(r.sender_id,auth.uid()) on conflict do nothing;
 insert into public.conversations(user_a,user_b) values(least(auth.uid(),r.sender_id),greatest(auth.uid(),r.sender_id)) on conflict do nothing returning id into c;
 if c is null then select id into c from public.conversations where user_a=least(auth.uid(),r.sender_id) and user_b=greatest(auth.uid(),r.sender_id); end if;
 update public.connection_requests set status='accepted' where id=r.id;
 insert into public.notifications(user_id,type,content) values(r.sender_id,'connection_accepted','Your connection request was accepted.');
 return c;
end $$;

create or replace function public.get_or_create_conversation(other_user_id uuid)
returns uuid language plpgsql security definer set search_path=public as $$
declare c uuid;
begin
 if other_user_id=auth.uid() then raise exception 'Invalid user'; end if;
 if not exists(select 1 from public.connections where user_id=auth.uid() and connected_user_id=other_user_id) then raise exception 'You must be connected before chatting'; end if;
 insert into public.conversations(user_a,user_b) values(least(auth.uid(),other_user_id),greatest(auth.uid(),other_user_id)) on conflict do nothing returning id into c;
 if c is null then select id into c from public.conversations where user_a=least(auth.uid(),other_user_id) and user_b=greatest(auth.uid(),other_user_id); end if;
 return c;
end $$;

grant execute on function public.accept_connection_request(uuid) to authenticated;
grant execute on function public.get_or_create_conversation(uuid) to authenticated;

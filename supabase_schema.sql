create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  username text unique not null,
  name text,
  country text,
  bio text,
  avatar_url text,
  online boolean default false,
  created_at timestamptz default now(),
  updated_at timestamptz default now()
);
create table if not exists public.connection_requests (
  id bigint generated by default as identity primary key,
  sender_id uuid references public.profiles(id) on delete cascade not null,
  receiver_id uuid references public.profiles(id) on delete cascade not null,
  status text not null default 'pending' check(status in ('pending','accepted','declined')),
  created_at timestamptz default now(),
  unique(sender_id,receiver_id)
);
create table if not exists public.connections (
  user_id uuid references public.profiles(id) on delete cascade not null,
  connected_user_id uuid references public.profiles(id) on delete cascade not null,
  created_at timestamptz default now(),
  primary key(user_id,connected_user_id)
);
create table if not exists public.conversations (
  id bigint generated by default as identity primary key,
  user_a uuid references public.profiles(id) on delete cascade not null,
  user_b uuid references public.profiles(id) on delete cascade not null,
  created_at timestamptz default now(),
  unique(user_a,user_b)
);
create table if not exists public.messages (
  id bigint generated by default as identity primary key,
  conversation_id bigint references public.conversations(id) on delete cascade not null,
  sender_id uuid references public.profiles(id) on delete cascade not null,
  body text not null,
  created_at timestamptz default now()
);
create table if not exists public.notifications (
  id bigint generated by default as identity primary key,
  user_id uuid references public.profiles(id) on delete cascade not null,
  type text not null,
  title text not null,
  body text,
  read boolean default false,
  created_at timestamptz default now()
);
